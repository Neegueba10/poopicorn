import { sheetBaker } from './sdfsheet.js';

/**
 * Stage runtime — one continuous, unbounded world of independently
 * parallaxed sprite stamps, drawn with `drawImage` onto a plain canvas.
 *
 * This is core/world.js's idea on the canvas stack: same stamps, same
 * parallax, same box collision, but the art is SDF sheets baked into
 * offscreen canvases instead of atlases baked into RetroBuffer RAM pages —
 * and the parallax rate and draw order belong to a LAYER here rather than to
 * every individual stamp. Neither module imports the other, so a game pays
 * for exactly the one it uses (the rule scene.js and world.js already live
 * by).
 *
 * Two of the world's source kinds do not survive the host change, and their
 * absence is the point:
 *
 *   - RAW DRAWINGS ARE GONE. A drawing is a drawShape replay into an indexed
 *     buffer; there is no canvas equivalent. The reason they existed — a
 *     backdrop too big for a RAM page — is gone with the pages, so a backdrop
 *     is now just a big sprite.
 *   - THE SOURCE CAP IS GONE. A world could load 8 atlases because 10 RAM
 *     pages exist and page 0 holds the palette. A canvas has no page budget.
 *
 * A stage is [sheets, layers, aabbs, objects?]:
 *
 *   sheets  — SDF sheet data arrays (see core/sdfsheet.js), one offscreen
 *             canvas each; a stamp's `k` indexes this list.
 *   layers  — PARALLAX LAYERS, far to near, in draw order. One layer is
 *             [rate, ...stamps]:
 *             rate  = parallax rate on BOTH axes for every stamp in the
 *                     layer; screen pos is x - cam * rate. 1 = gameplay
 *                     plane, <1 far, >1 near.
 *             stamps— flat, stride 5: [k, i, x, y, fx]
 *             k     = sheets[k], sprite id `i` in it. Sheet ids are
 *                     positional and permanent, so a stage that references
 *                     sprite 17 keeps meaning it.
 *             x, y  = world position of the top-left, signed, unbounded.
 *             fx    = 1 to mirror horizontally.
 *
 *             **THE PARALLAX RATE AND THE DRAW ORDER LIVE ON THE LAYER, NOT
 *             ON THE STAMP.** They used to be two more numbers on every one
 *             of them — a `rate` and a `depth` — which is two numbers per
 *             stamp to say what a whole band of them always shared. Draw
 *             order is now simply the order things are in: layers in list
 *             order, stamps in list order within a layer. Nothing sorts, at
 *             build time or run time, and there is no ordering contract a
 *             hand-edited file can silently violate.
 *   aabbs   — flat, stride 5: [type, x0, y0, x1, y1] with x1/y1 EXCLUSIVE
 *             (same convention as world.js and scene.js). type 0 = solid,
 *             other values game-defined. Plain boxes only — no slopes.
 *             Coords are gameplay-plane (rate 1) world space.
 *   objects — optional, variable stride: [x, y, k, i, fx, n, k0, v0, ...]
 *             per object. k/i/fx address a sprite exactly like a stamp
 *             (k = -2 for a logic-only marker with no visual); n is the KV
 *             pair count, k a string and v a number — free game-defined data,
 *             the same "the tool has zero opinion" contract world.js and
 *             scene.js use.
 *
 * Objects and AABBs are deliberately NOT view-culled: a linear scan over a
 * few hundred boxes is a few thousand compares, and culling correctness
 * depends on camera state, which is a bug farm.
 *
 * Files generated by the stagetool live in src/js/stages/; see
 * tools/stagetool/README.md for the format and editor.
 */

/**
 * Start baking every sheet of stage `w`, one offscreen canvas each.
 *
 * PROGRESSIVE, like every other SDF bake: the marching is the loading screen,
 * so this hands back a stepper and the game drives it from its own loop. The
 * RECT TABLES ARE READY IMMEDIATELY — sheetBaker packs in its constructor — so
 * a stage can be measured, culled and hit-tested before a ray is marched.
 *
 * @param {any[]} w stage [sheets, layers, aabbs, objects?]
 * @param {Uint8Array} pal palette RGB
 * @param {number} [sheetW] packing width of each baked canvas
 * @param {object} [opts] SDF constructor options
 * @returns {{ step(ms?: number): void, done(): boolean, progress(): number,
 *   srcs: { rects: Int16Array, canvas: HTMLCanvasElement }[] }}
 */
export function stageBaker(w, pal, sheetW = 512, opts = {}) {
  const srcs = w[0].map(s => sheetBaker(s, pal, sheetW, opts));
  let n = 0;
  return {
    step(ms = 8) {
      const t0 = Date.now();
      while (n < srcs.length) {
        srcs[n].step(Math.max(1, ms - (Date.now() - t0)));
        if (!srcs[n].done()) return;         // resume mid-sheet next frame
        n++;
        if (Date.now() - t0 >= ms) return;
      }
    },
    done: () => n >= srcs.length,
    progress: () => (srcs.length
      ? srcs.reduce((a, b) => a + b.progress(), 0) / srcs.length : 1),
    srcs,
  };
}

/**
 * Draw layers [l0, l1) onto an `sw` x `sh` screen, culled to it, at camera
 * (cx, cy). Draw the player and other actors between two calls split on a
 * LAYER INDEX — drawStage(ctx, w, srcs, cx, cy, W, H, 0, 3) then the actors
 * then drawStage(ctx, w, srcs, cx, cy, W, H, 3) — so the near layers occlude
 * them. A game that wants a stamp in front of the player puts it in a layer
 * after the split.
 *
 * THE SCREEN SIZE IS A PARAMETER, not `ctx.canvas`: `canvas` is on the
 * property-crunch allowlist (scripts/crunch-props.js, RetroBuffer owns a
 * field by that name), so reading it off a DOM object here would be renamed
 * with it and come back undefined in the BUILT game while dev worked fine.
 * Quoting does not save it either — terser's `compress.properties` turns
 * `ctx['canvas']` back into `ctx.canvas` before the mangler ever sees it.
 *
 * `srcs` is stageBaker's; an unfinished bake draws whatever has landed so
 * far rather than failing, because a rect exists before its pixels do.
 *
 * @param {CanvasRenderingContext2D} ctx
 * @param {any[]} w
 * @param {{ rects: Int16Array, canvas: HTMLCanvasElement }[]} srcs
 */
export function drawStage(ctx, w, srcs, cx = 0, cy = 0, sw = 1e9, sh = 1e9, l0 = 0, l1 = 1e9) {
  const L = w[1];
  for (let n = l0; n < l1 && n < L.length; n++) {
    const s = L[n], rate = s[0];
    const ox = cx * rate, oy = cy * rate;
    for (let i = 1; i < s.length; i += 5) {
      const a = srcs[s[i]];
      if (!a) continue;
      const t = a.rects, j = s[i + 1] * 4, gw = t[j + 2], gh = t[j + 3];
      if (!gw) continue;            // tombstone, or an id past the end
      const x = (s[i + 2] - ox) | 0, y = (s[i + 3] - oy) | 0;
      if (x + gw <= 0 || x >= sw || y + gh <= 0 || y >= sh) continue;
      if (s[i + 4]) {
        // A mirrored sprite costs a transform, not a second baked copy: the
        // flip is the compositor's, and these sprites have hard alpha, so
        // nothing about the pixels changes.
        ctx.save();
        ctx.translate(x + gw, y);
        ctx.scale(-1, 1);
        ctx.drawImage(a.canvas, t[j], t[j + 1], gw, gh, 0, 0, gw, gh);
        ctx.restore();
      } else {
        ctx.drawImage(a.canvas, t[j], t[j + 1], gw, gh, x, y, gw, gh);
      }
    }
  }
}

/**
 * Index into w[2] of the first AABB of `type` overlapping the (exclusive)
 * box [x0,x1) x [y0,y1), or -1. Pass `from = hit + 5` to keep scanning for
 * further overlaps. The hit box is w[2][i+1..i+4] — y0 (i+2) is the surface
 * a controller stands on.
 * @returns {number}
 */
export function hitStage(w, x0, y0, x1, y1, type = 0, from = 0) {
  const a = w[2];
  for (let i = from; i < a.length; i += 5)
    if (a[i] == type && x0 < a[i + 3] && a[i + 1] < x1 && y0 < a[i + 4] && a[i + 2] < y1)
      return i;
  return -1;
}

/**
 * Walk the variable-stride object list, calling fn(i, x, y, k, id, fx) with
 * `i` the object's flat index (pass it back to kvOf). Games run this once at
 * load to build their own live lists.
 */
export function eachObject(w, fn) {
  const o = w[3] || [];
  for (let i = 0; i < o.length; i += 6 + o[i + 5] * 2)
    fn(i, o[i], o[i + 1], o[i + 2], o[i + 3], o[i + 4]);
}

/** Value of `key` in the object at flat index `i`, or undefined. */
export function kvOf(w, i, key) {
  const o = w[3], n = o[i + 5];
  for (let j = 0; j < n; j++) if (o[i + 6 + j * 2] === key) return o[i + 7 + j * 2];
}
